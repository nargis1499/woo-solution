import type { CurrencyCode, Money } from "@/lib/money";
export const COMPARISONS = ["gt", "gte", "lt", "lte", "eq", "ne"] as const;
export type NumericRule = Partial<Record<(typeof COMPARISONS)[number], number>>;
export type ProductFilters = {
  scope: "products" | "variations" | "skus";
  stock?: NumericRule;
  price?: NumericRule;
  anyOf?: Array<{ stock?: NumericRule; price?: NumericRule }>;
  id?: string;
  productId?: string;
  ids?: string[];
  search?: string;
  name?: string;
  sku?: string;
  brand?: string;
  category?: string;
  categorySlug?: string;
  categoryId?: string;
  categorySlugs?: string[];
  status: "active" | "draft" | "all";
  variationStatus: "active" | "draft" | "all";
  type: "simple" | "variable" | "all";
  stockStatus: "all" | "tracked" | "untracked" | "in_stock" | "out_of_stock";
  featured?: boolean;
  onSale?: boolean;
  currency?: CurrencyCode;
  createdFrom?: string;
  createdTo?: string;
  updatedFrom?: string;
  updatedTo?: string;
  sortBy: "name" | "stock" | "price" | "created_at" | "updated_at";
  sortDirection: "asc" | "desc";
  page: number;
  limit: number;
};
export type ProductQueryRow = {
  id: string;
  product_id: string;
  variation_id: string | null;
  name: string;
  product_name: string;
  slug: string;
  sku: string | null;
  brand: string | null;
  type: "simple" | "variable";
  category: string | null;
  category_slug: string | null;
  stock: number | null;
  stock_managed: boolean;
  price_micros: number | null;
  compare_at_price_micros: number | null;
  on_sale: boolean;
  featured: boolean;
  status: "active" | "draft";
  variation_status: "active" | "draft" | null;
  created_at: string;
  updated_at: string;
  image_url: string | null;
  image_path: string | null;
};
export type ProductQueryReport = {
  generatedAt: string;
  filters: ProductFilters;
  money: Money;
  total: number;
  hasMore: boolean;
  metrics: {
    tracked: number;
    untracked: number;
    trackedUnits: number;
    outOfStock: number;
    lowStock: number;
  };
  rows: ProductQueryRow[];
};
export type AiProductQueryWidget = ProductQueryReport & {
  id: string;
  kind: "product_query";
  initialVisibleRows: number;
};
